def merge(*ds):
    out = {}
    for d in ds:
        out.update(d)
    return out


def check_lut(lut, name=""):
    src = {k.lower() for k in lut}
    dst = {v.lower() for k, v in lut.items() if k.lower() != v.lower()}
    bad = src & dst
    assert not bad, (name, "LUT 결과가 원래 색과 겹침(멱등 아님)", bad)
    return True


